import os
import re

import joblib
import numpy as np
import shap
from lime.lime_text import LimeTextExplainer


# Paths are relative to the project root, so this module can be run
# from different working directories.
PROJECT_ROOT = os.path.dirname(
    os.path.dirname(os.path.abspath(__file__))
)
MODEL_DIR = os.path.join(PROJECT_ROOT, "models")

TFIDF_PATH = os.path.join(MODEL_DIR, "tfidf_vectorizer.pkl")
MODEL_PATH = os.path.join(MODEL_DIR, "logistic_regression.pkl")

LABEL_MAP = {0: "FAKE", 1: "REAL"}
CLASS_NAMES = ["FAKE", "REAL"]


def load_artifacts():
    """Load the trained vectorizer and classification model."""
    missing_files = [
        path for path in (TFIDF_PATH, MODEL_PATH)
        if not os.path.isfile(path)
    ]
    if missing_files:
        missing = ", ".join(missing_files)
        raise FileNotFoundError(
            f"Required model artifact(s) not found: {missing}"
        )

    vectorizer = joblib.load(TFIDF_PATH)
    classifier = joblib.load(MODEL_PATH)
    return vectorizer, classifier


tfidf, logistic_regression = load_artifacts()


def preprocess_text(text):
    """Normalize news text using the model's expected preprocessing."""
    if not isinstance(text, str):
        text = str(text)

    text = text.lower()
    text = re.sub(r"https?://\S+|www\.\S+", " ", text)
    text = re.sub(r"<.*?>", " ", text)
    text = re.sub(r"[^a-z\s]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def lime_predict(texts):
    """Return class probabilities for the text samples generated by LIME."""
    cleaned_texts = [preprocess_text(text) for text in texts]
    features = tfidf.transform(cleaned_texts)
    return logistic_regression.predict_proba(features)


def get_lime_explanation(text, num_features=10):
    """Return words that influenced LIME's local prediction explanation."""
    if num_features < 1:
        raise ValueError("num_features must be at least 1.")

    explainer = LimeTextExplainer(class_names=CLASS_NAMES)
    explanation = explainer.explain_instance(
        text,
        lime_predict,
        num_features=num_features,
    )

    return [
        {"word": word, "weight": round(float(weight), 4)}
        for word, weight in explanation.as_list()
    ]


# Build the SHAP explainer once and reuse it for later predictions.
# The background data uses the same vectorizer as the classifier.
_shap_background = tfidf.transform(["sample news article"])
shap_explainer = shap.LinearExplainer(
    logistic_regression,
    _shap_background,
)


def get_shap_explanation(text, num_features=10):
    """Return the strongest SHAP feature contributions for the input text."""
    if num_features < 1:
        raise ValueError("num_features must be at least 1.")

    cleaned_text = preprocess_text(text)
    features = tfidf.transform([cleaned_text])
    shap_result = shap_explainer(features)

    values = np.asarray(shap_result.values)

    # For a binary classifier, SHAP can return either a 2-D array
    # or an array with an additional class dimension, depending on
    # the installed SHAP version and model configuration.
    if values.ndim == 3:
        values = values[0, :, -1]
    elif values.ndim == 2:
        values = values[0]
    else:
        values = values.reshape(-1)

    feature_names = tfidf.get_feature_names_out()
    active_indices = features.getnnz(axis=0)
    active_set = set(np.flatnonzero(np.asarray(active_indices).ravel()))

    ranked_indices = np.argsort(np.abs(values))[::-1]
    explanation = []

    for index in ranked_indices:
        if index not in active_set:
            continue

        explanation.append(
            {
                "word": feature_names[index],
                "shap_value": round(float(values[index]), 6),
            }
        )

        if len(explanation) >= num_features:
            break

    return explanation


def explain_news(text, num_features=10):
    """
    Predict a FAKE/REAL label and return LIME and SHAP explanations.

    The confidence field is the model's predicted-class probability.
    It should not be interpreted as a guarantee of factual accuracy.
    """
    if not isinstance(text, str) or not text.strip():
        raise ValueError("News text cannot be empty.")

    if num_features < 1:
        raise ValueError("num_features must be at least 1.")

    cleaned_text = preprocess_text(text)
    features = tfidf.transform([cleaned_text])

    prediction = int(logistic_regression.predict(features)[0])
    probabilities = logistic_regression.predict_proba(features)[0]

    return {
        "model": "Logistic Regression",
        "prediction": LABEL_MAP.get(prediction, str(prediction)),
        "confidence": round(float(np.max(probabilities)), 4),
        "lime": get_lime_explanation(cleaned_text, num_features),
        "shap": get_shap_explanation(cleaned_text, num_features),
    }


if __name__ == "__main__":
    test_cases = [
        (
            "The government announced a new economic policy "
            "to increase employment and investment."
        ),
        (
            "Scientists discovered that drinking a special "
            "juice can make humans live forever."
        ),
    ]

    print("=" * 68)
    print("NEWS CLASSIFICATION — EXPLAINABILITY TEST")
    print("=" * 68)

    for number, news_text in enumerate(test_cases, start=1):
        print(f"\n{'-' * 68}\nTEST {number}\n{'-' * 68}")
        print(f"\nInput: {news_text}")

        try:
            result = explain_news(news_text, num_features=10)
        except Exception as error:
            print(f"Could not generate the explanation: {error}")
            continue

        print(f"\nPrediction: {result['prediction']}")
        print(f"Model confidence: {result['confidence']:.4f}")

        print("\nLIME explanation:")
        for item in result["lime"]:
            print(f"  {item['word']:<25} {item['weight']:+.4f}")

        print("\nSHAP explanation:")
        for item in result["shap"]:
            print(f"  {item['word']:<25} {item['shap_value']:+.6f}")

    print("\nExplainability test finished.")
